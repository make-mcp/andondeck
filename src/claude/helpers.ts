import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";

import type { ClaudeLocation } from "./env.js";
import { execWhenFound, shellQuote } from "./locate.js";

/**
 * Small scripts generated next to Claude Code's configuration.
 *
 * They are generated rather than shipped for two reasons: they have to live on
 * the same filesystem as Claude Code, which on Windows may be inside WSL; and
 * shell source must never travel through `wsl.exe`'s argument parsing, which
 * silently mangles quoting and leaves `$HOME` empty. Delivering scripts as
 * files and passing only plain arguments is the one approach that holds up
 * across install methods.
 */
export const HELPERS = {
	/** Long-polls the bridge and exits 2 to wake an idle session. */
	idleWake: "idle-wake.mjs",
	/** Finds a usable Node, then runs {@link HELPERS.idleWake}. */
	idleWakeWrapper: "idle-wake.sh",
	/** Finds the Claude Code executable and passes its arguments through. */
	runClaude: "run-claude.sh",
	/** Reports whether the bridge is reachable from Claude Code's side. */
	reach: "reach.sh",
	/** Status line tee: posts Claude Code's status JSON, then runs the user's own status line. */
	statusLine: "deck-statusline.sh",
	/** The same, for Claude Code running natively on Windows. */
	statusLineNode: "deck-statusline.mjs",
	/** The user's own status line, kept so it can be chained and restored. */
	statusLineOriginal: "statusline-original.json",
} as const;

export type HelperOptions = {
	location: ClaudeLocation;
	/** Bridge base URL the idle-wake helper long-polls. */
	baseUrl: string;
	token: string;
	/** The user's own status line command, run after the deck has had its copy. */
	statusLineCommand?: string;
};

/**
 * Status line tee for POSIX shells.
 *
 * Claude Code hands its status line a JSON snapshot that, for subscribers,
 * includes the 5-hour and weekly plan limits with their reset times — data no
 * hook carries. This posts that snapshot to the bridge in the background, so
 * the line itself is never slowed down, and then runs whatever status line the
 * user already had, exactly as before.
 */
function statusLineSource(options: HelperOptions): string {
	const url = `${options.baseUrl.replace(/\/+$/, "")}/status`;
	const original = options.statusLineCommand?.trim();

	return `#!/bin/sh
${BANNER}
input=$(cat)
url=${shellQuote(url)}
token=${shellQuote(options.token)}

if command -v curl >/dev/null 2>&1; then
	printf '%s' "$input" | curl -fsS -m 2 -o /dev/null -H 'content-type: application/json' -H "x-claude-deck-token: $token" --data-binary @- "$url" >/dev/null 2>&1 &
elif command -v wget >/dev/null 2>&1; then
	wget -q -T 2 -O /dev/null --header='content-type: application/json' --header="x-claude-deck-token: $token" --post-data="$input" "$url" >/dev/null 2>&1 &
fi
${
	original
		? `
# The status line that was configured before Claude Deck.
original=${shellQuote(original)}
if command -v bash >/dev/null 2>&1; then
	printf '%s' "$input" | bash -c "$original"
else
	printf '%s' "$input" | sh -c "$original"
fi`
		: ""
}
`;
}

/** Status line tee for Claude Code running natively on Windows, where `sh` may not exist. */
function statusLineNodeSource(options: HelperOptions): string {
	const url = `${options.baseUrl.replace(/\/+$/, "")}/status`;

	return `// Generated by Claude Deck. Safe to delete; the plugin rewrites it on connect.
import { spawnSync } from "node:child_process";

let raw = "";
for await (const chunk of process.stdin) raw += chunk;

const original = ${JSON.stringify(options.statusLineCommand?.trim() ?? "")};
if (original) {
	const result = spawnSync(original, { shell: true, input: raw, encoding: "utf8", windowsHide: true });
	process.stdout.write(result.stdout ?? "");
}

await fetch(${JSON.stringify(url)}, {
	method: "POST",
	headers: { "content-type": "application/json", "x-claude-deck-token": ${JSON.stringify(options.token)} },
	body: raw,
	signal: AbortSignal.timeout(1500),
}).catch(() => {});
`;
}

/** Node source for the idle-wake helper. */
function idleWakeSource(options: HelperOptions): string {
	return `// Generated by Claude Deck. Safe to delete; the plugin rewrites it on connect.
// Long-polls the Stream Deck bridge for a prompt queued while this session is
// idle, then exits 2 so Claude Code wakes up and acts on it.
const url = ${JSON.stringify(`${options.baseUrl.replace(/\/+$/, "")}/wait`)};
const token = ${JSON.stringify(options.token)};

let raw = "";
for await (const chunk of process.stdin) raw += chunk;

let sessionId;
try {
	sessionId = JSON.parse(raw || "{}").session_id;
} catch {
	process.exit(0);
}
if (!sessionId) process.exit(0);

let response;
try {
	response = await fetch(url, {
		method: "POST",
		headers: { "content-type": "application/json", "x-claude-deck-token": token },
		body: JSON.stringify({ session_id: sessionId }),
	});
} catch {
	process.exit(0);
}

if (!response.ok) process.exit(0);
const { text } = await response.json().catch(() => ({}));
if (!text) process.exit(0);

process.stderr.write(String(text));
process.exit(2);
`;
}

const BANNER = "# Generated by Claude Deck. Safe to delete; the plugin rewrites it on connect.";

/** Wrapper that locates Node before running the idle-wake helper. */
function idleWakeWrapperSource(options: HelperOptions): string {
	const helper = `${options.location.dataDirForClaude}/${HELPERS.idleWake}`;

	return `#!/bin/sh
${BANNER}
# Finds a usable node, then hands over to the idle-wake helper.

${execWhenFound("node", [helper], "# No node available: exiting 0 leaves Claude Code untouched.\nexit 0")}
`;
}

/** Wrapper that locates the Claude Code executable and forwards its arguments. */
function runClaudeSource(): string {
	return `#!/bin/sh
${BANNER}
# Finds the claude executable and passes every argument straight through.

${execWhenFound("claude", ['"$@"'], 'echo "claude-deck: could not find the claude executable" >&2\nexit 127', { raw: true })}
`;
}

/** Connectivity probe, using whatever the distribution happens to have. */
function reachSource(): string {
	return `#!/bin/sh
${BANNER}
# Usage: reach.sh <host> <port>  ->  prints "ok", "no" or "unknown".
host=$1
port=$2

if command -v curl >/dev/null 2>&1; then
	curl -fsS -m 4 -o /dev/null "http://$host:$port/health" && echo ok || echo no
	exit 0
fi

if command -v wget >/dev/null 2>&1; then
	wget -q -T 4 -O /dev/null "http://$host:$port/health" && echo ok || echo no
	exit 0
fi

if [ -x /bin/bash ]; then
	/bin/bash -c "exec 3<>/dev/tcp/$host/$port" >/dev/null 2>&1 && echo ok || echo no
	exit 0
fi

echo unknown
`;
}

/**
 * Writes every helper script, creating the directory if needed.
 * @param options Where to write them and what the bridge looks like.
 * @returns The directory they were written to, as this process sees it.
 */
export async function writeHelpers(options: HelperOptions): Promise<string> {
	const dir = options.location.dataDir;
	await mkdir(dir, { recursive: true });

	await Promise.all([
		writeFile(join(dir, HELPERS.idleWake), idleWakeSource(options), "utf8"),
		writeFile(join(dir, HELPERS.idleWakeWrapper), idleWakeWrapperSource(options), "utf8"),
		writeFile(join(dir, HELPERS.runClaude), runClaudeSource(), "utf8"),
		writeFile(join(dir, HELPERS.reach), reachSource(), "utf8"),
		writeFile(join(dir, HELPERS.statusLine), statusLineSource(options), "utf8"),
		writeFile(join(dir, HELPERS.statusLineNode), statusLineNodeSource(options), "utf8"),
	]);

	return dir;
}

/** Path of a helper, spelled the way Claude Code's own filesystem sees it. */
export function helperPath(location: ClaudeLocation, helper: keyof typeof HELPERS): string {
	const separator = location.kind === "wsl" ? "/" : location.dataDirForClaude.includes("\\") ? "\\" : "/";
	return `${location.dataDirForClaude}${separator}${HELPERS[helper]}`;
}
